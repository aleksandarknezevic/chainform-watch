#!/usr/bin/env python3
"""Create watch configs for targets.json entries that do not have one yet.

    RPC_URL=https://... python3 scripts/bootstrap.py [--summary summary.md]

For each missing file, `chainform import` snapshots the contract's current
on-chain values, so a new config always starts in sync with the chain. The ABIs
in abis/ list view functions only, which makes every value an `expect`
assertion: this repo watches, it never proposes calls.

A target whose import fails (a getter reverts, a wrong address) is reported and
skipped; the others are still written.

Exit codes: 0 nothing failed, 3 some targets failed, 2 bad input.
"""

import argparse
import json
import os
import re
import subprocess
import sys

EXPLORERS = {1: "https://etherscan.io/address/"}


def resource_name(path):
    """watch/aave-v3-pool.hcl -> aaveV3Pool"""
    parts = re.split(r"[^A-Za-z0-9]+", os.path.splitext(os.path.basename(path))[0])
    parts = [p for p in parts if p]
    return parts[0].lower() + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def header(t, chain_id):
    lines = [f"# {t['title']}", "#"]
    for chunk in wrap(t.get("note", ""), 76):
        lines.append(f"# {chunk}")
    lines.append("#")
    if t.get("source"):
        lines.append(f"# Source: {t['source']}")
    if chain_id in EXPLORERS:
        lines.append(f"# Contract: {EXPLORERS[chain_id]}{t['address']}")
    lines.append(f"# tags: {t['tags']}")
    lines.append("#")
    lines.append(f"# Generated by scripts/bootstrap.py from the on-chain state.")
    return "\n".join(lines) + "\n\n"


def wrap(text, width):
    words, line, out = text.split(), "", []
    for w in words:
        if line and len(line) + 1 + len(w) > width:
            out.append(line)
            line = w
        else:
            line = f"{line} {w}".strip()
    if line:
        out.append(line)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--targets", default="targets.json")
    ap.add_argument("--summary")
    args = ap.parse_args()

    rpc = os.environ.get("RPC_URL")
    if not rpc:
        print("error: set RPC_URL", file=sys.stderr)
        return 2
    try:
        with open(args.targets) as f:
            targets = json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    created, failed = [], []
    for t in targets:
        path = t["file"]
        if os.path.exists(path):
            continue
        chain_id = int(t.get("chain_id", 1))
        cmd = [
            "chainform", "import",
            "--address", t["address"],
            "--abi", t["abi"],
            "--name", resource_name(path),
            "--chain-id", str(chain_id),
            "--chain-name", t.get("chain_name", "ethereum"),
            "--rpc", rpc,
        ]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            failed.append((t, r.stderr.strip().splitlines()[-1:] or ["import failed"]))
            continue

        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(header(t, chain_id) + r.stdout)

        v = subprocess.run(["chainform", "validate", "-f", path], capture_output=True, text=True)
        if v.returncode != 0:
            os.remove(path)
            failed.append((t, (v.stderr or v.stdout).strip().splitlines()[-1:]))
            continue
        created.append(t)

    out = []
    if created:
        out += ["Created from the current on-chain state:", ""]
        out += [f"- `{t['file']}` - {t['title']}" for t in created]
    if failed:
        out += ["", "**Failed** (fix the address/ABI in targets.json and re-run):", ""]
        out += [f"- `{t['file']}` - {err[0]}" for t, err in failed]
    if not out:
        out = ["Every target already has a config."]
    text = "\n".join(out) + "\n"
    if args.summary:
        with open(args.summary, "w") as f:
            f.write(text)
    print(text)

    return 3 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
